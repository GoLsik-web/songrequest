// Package spotifyapp читает то, что играет, прямо у программы Spotify на этом
// же компьютере — из заголовка её окна.
//
// Зачем это вообще понадобилось. «Что играет у стримера» приложение спрашивало
// у Spotify по сети, раз в секунду. За вечер стрима это тысячи запросов, а
// норма у Client ID в режиме разработки (другого у стримера не будет — он
// заводит его на своём аккаунте) тесная. 29.08 Spotify ответил на это паузой в
// четыре с половиной часа: панель перестала показывать играющий трек, заказы
// перестали играть, и выглядело это как поломка всего приложения сразу.
//
// А программа Spotify всё это время писала имя трека прямо в заголовок своего
// окна — бесплатно, мгновенно и без всякой сети. Оттуда и берём: панель
// показывает трек всегда, даже когда Spotify закрыл приложению доступ к
// плееру, а по сети приложение ходит только за тем, чего в заголовке нет
// (обложка, длительность, точное положение) — и только когда трек сменился.
//
// Чего здесь нет и быть не может: положения внутри трека, длительности,
// обложки и признака «поставили на паузу посреди трека» (Spotify в этом
// случае заголовок не меняет). Всё это по-прежнему берётся по сети, просто
// несравнимо реже.
package spotifyapp

import "strings"

// Status — что удалось узнать у программы Spotify на этом компьютере.
type Status int

const (
	// Unknown — программы Spotify нет (закрыта, или стример слушает с
	// телефона или из браузера). Читать нечего, остаётся спрашивать по сети.
	Unknown Status = iota
	// Idle — программа есть, музыка в ней стоит.
	Idle
	// Playing — играет вот это.
	Playing
)

// Track — то, что удалось прочитать у программы Spotify.
type Track struct {
	Artist string
	Title  string
}

// Same отвечает, тот же это трек или уже другой.
func (t Track) Same(other Track) bool {
	return t.Artist == other.Artist && t.Title == other.Title
}

// Empty — читать нечего.
func (t Track) Empty() bool { return t.Artist == "" && t.Title == "" }

// idleTitles — заголовки, которые Spotify показывает, когда музыка не играет.
// Список короткий и проверенный: у разных подписок и языков заголовок разный,
// но все они начинаются со слова Spotify, а имя трека — никогда.
var idleTitles = []string{"spotify", "spotify premium", "spotify free"}

// parseTitle разбирает заголовок окна «Артист - Название».
//
// Разделитель — первое « - » с пробелами: в названиях треков дефис попадается
// сплошь и рядом («Sk8er Boi - Remastered»), а вот в имени артиста почти
// никогда.
func parseTitle(title string) (Track, Status) {
	title = strings.TrimSpace(title)
	if title == "" {
		return Track{}, Unknown
	}
	for _, idle := range idleTitles {
		if strings.EqualFold(title, idle) {
			return Track{}, Idle
		}
	}

	i := strings.Index(title, " - ")
	if i <= 0 {
		// Что-то не похожее ни на трек, ни на известный простой заголовок.
		// Показывать это в кадре нельзя, но и «музыка стоит» отсюда не
		// следует: пусть решает опрос по сети.
		return Track{}, Unknown
	}
	artist := strings.TrimSpace(title[:i])
	name := strings.TrimSpace(title[i+3:])
	if artist == "" || name == "" {
		return Track{}, Unknown
	}
	return Track{Artist: artist, Title: name}, Playing
}
