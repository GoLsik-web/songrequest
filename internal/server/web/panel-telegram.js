  const $ = (id) => document.getElementById(id);
  const t = (text) => I18N.t(text);
  let dirty = false, busy = false;
  let pairing = false;
  function modeLayout() {
    const shared = $("tg-mode").value === "shared";
    $("tg-shared").hidden = !shared;
    $("tg-personal").hidden = shared;
    $("tg-forget").hidden = shared;
  }
  $("tg-mode").onchange = () => { dirty = true; modeLayout(); };
  const box = $("telegram-settings");
  const status = $("tg-status");
  box.addEventListener("input", () => { dirty = true; });
  function note(text, bad) { status.textContent = text; status.className = "state " + (bad ? "bad" : ""); }
  async function load() {
    if (busy) return;
    try {
      const res = await fetch("/api/telegram");
      if (!res.ok) throw new Error(t("Не получилось связаться с приложением."));
      const d = await res.json(), s = d.settings;
      if (!dirty) {
        $("tg-mode").value = s.mode || (d.has_token ? "personal" : "shared");
        $("tg-relay-url").value = s.relay_url || d.shared_relay_url || "";
        $("tg-enabled").checked = s.enabled;
        $("tg-owner").value = s.owner_id || "";
        $("tg-auto").checked = s.auto_recap;
        $("tg-notify").checked = s.notify_orders;
        $("tg-channel").value = s.publish_channel || "";
      }
      modeLayout();
      $("tg-pair-revoke").hidden = !d.shared_link;
      if (d.shared_link && s.mode === "shared" && !s.owner_id) pairing = true;
      $("tg-token").placeholder = t(d.has_token ? "Токен сохранён" : "Токен от BotFather");
      const open = $("tg-open");
      open.hidden = !/^[a-zA-Z0-9_]+$/.test(d.username || "");
      if (!open.hidden) open.href = "https://t.me/" + d.username;
      note(d.note ? t(d.note) : t(!s.enabled ? "Telegram выключен" : d.connected ? "Telegram подключён" : "Подключаюсь к Telegram…"), !!d.note);
    } catch (e) { note(e.message, true); }
  }
  async function save(forget) {
    if (busy) return;
    if (forget && !confirm(t("Отключить Telegram и удалить сохранённый токен?"))) return;
    const owner = $("tg-owner").value.trim();
    if (owner && (!/^\d+$/.test(owner) || !Number.isSafeInteger(Number(owner)) || Number(owner) <= 0)) {
      note(t("Проверь свой Telegram ID: нужны только цифры."), true); return;
    }
    busy = true;
    $("tg-save").disabled = $("tg-forget").disabled = true;
    try {
      const response = await fetch("/api/telegram", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({
        enabled: !forget && $("tg-enabled").checked, owner_id: Number(owner) || 0,
        mode: $("tg-mode").value,
        auto_recap: $("tg-auto").checked, notify_orders: $("tg-notify").checked,
        publish_channel: $("tg-channel").value.trim(), token: forget || $("tg-mode").value === "shared" ? "" : $("tg-token").value.trim(), forget,
      }) });
      if (!response.ok) throw new Error(t((await response.text()).trim()));
      $("tg-token").value = ""; dirty = false;
      note(t("Настройки Telegram сохранены"), false);
    } catch (e) { note(e.message, true); }
    finally { busy = false; $("tg-save").disabled = $("tg-forget").disabled = false; }
    await load();
  }
  $("tg-save").onclick = () => save(false);
  $("tg-test").onclick = async () => {
    if (busy) return;
    if (dirty) { note(t("Сначала сохрани настройки Telegram."), true); return; }
    busy = true;
    $("tg-test").disabled = true;
    try {
      const response = await fetch("/api/telegram/test", { method: "POST" });
      if (!response.ok) throw new Error(t((await response.text()).trim()));
      note(t("Тестовое сообщение отправлено. Проверь чат со своим ботом."), false);
    } catch (e) { note(e.message, true); }
    finally { busy = false; $("tg-test").disabled = false; }
  };
  $("tg-forget").onclick = () => save(true);
  async function pairingCall(path, body) {
    const response = await fetch(path, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body || {}) });
    if (!response.ok) throw new Error((await response.text()).trim());
    return response.json();
  }
  $("tg-pair").onclick = async () => {
    if (busy) return;
    busy = true; $("tg-pair").disabled = true;
    try {
      const data = await pairingCall("/api/telegram/pair", { url: $("tg-relay-url").value.trim() });
      const link = $("tg-pair-link"); link.href = data.link; link.hidden = false;
      $("tg-pair-status").textContent = t("Открой общего бота, нажми Старт и вернись сюда для подтверждения аккаунта.");
      pairing = true;
      $("tg-pair-confirm").hidden = true;
    } catch (error) { note(error.message, true); }
    finally { busy = false; $("tg-pair").disabled = false; }
  };
  $("tg-pair-confirm").onclick = async () => {
    if (busy) return;
    busy = true;
    try {
      const data = await pairingCall("/api/telegram/pair/confirm");
      $("tg-owner").value = data.owner_id; $("tg-enabled").checked = true;
      $("tg-mode").value = "shared";
      pairing = false; $("tg-pair-confirm").hidden = $("tg-pair-link").hidden = true;
      $("tg-pair-status").textContent = t("Telegram подключён к этому приложению.");
    } catch (error) { note(error.message, true); }
    finally { busy = false; }
    await save(false);
  };
  $("tg-pair-revoke").onclick = async () => {
    if (busy) return;
    busy = true;
    try {
      await pairingCall("/api/telegram/pair/revoke");
      pairing = false; dirty = false; $("tg-pair-confirm").hidden = $("tg-pair-link").hidden = true;
      $("tg-pair-status").textContent = t("Приложение отвязано от Telegram.");
    } catch (error) { note(error.message, true); }
    finally { busy = false; }
    await load();
  };
  setInterval(async () => {
    if (!pairing || busy || document.hidden) return;
    try {
      const data = await pairingCall("/api/telegram/pair/status");
      $("tg-pair-confirm").hidden = data.state !== "confirm";
      if (data.state === "confirm") $("tg-pair-status").textContent = t("Подтверди свой Telegram-аккаунт:") + " " + (data.name || "") + " · ID " + data.owner_id;
      if (data.state === "expired") { pairing = false; $("tg-pair-status").textContent = t("Ссылка истекла. Начни подключение заново."); }
    } catch (error) { $("tg-pair-status").textContent = error.message; }
  }, 4000);
  new MutationObserver(() => { if (!$("settings").hidden) load(); }).observe($("settings"), { attributes: true, attributeFilter: ["hidden"] });
  setInterval(() => { if (!document.hidden && !$("settings").hidden) load(); }, 10000);
  load();
  I18N.onChange(load);
